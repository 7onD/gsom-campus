"""Собирает src/data/floor1.json: аудитории из OCR (data/ocr-floor1.json) и вручную размеченные коридоры.
Координаты — пиксели public/plans/floor1.jpg. Запуск: python3 -I tools/build_floor1.py"""
import json, re

ocr = json.load(open("data/ocr-floor1.json", encoding="utf8"))

# Аудитории из OCR. Строки с несколькими номерами делим по ширине рамки.
raw = []
for it in ocr:
    nums = re.findall(r"\b\d{3,4}\b", it["text"])
    if not nums or re.search(r"[A-Za-zА-Яа-я]", it["text"]) or "-" in it["text"]:
        continue
    for i, n in enumerate(nums):
        cx = it["x"] + it["w"] * (i + 0.5) / len(nums)
        raw.append((n, round(cx), round(it["y"] + it["h"] / 2)))

# Номера, встречающиеся на плане дважды. Второе вхождение получает суффикс -2.
names = {
    "1103": "Комендант", "1104": "Охрана", "1124": "Служба по работе с молодёжью, Студсовет",
    "1122": "Офис директора", "1301": "Конференц-зал", "014": "Библиотека",
}
dups = {}
for n, x, y in raw:
    dups.setdefault(n, []).append((x, y))

anchors = []
for n, pts in sorted(dups.items()):
    pts.sort(key=lambda p: p[1])
    for k, (x, y) in enumerate(pts):
        rid = n if k == 0 else f"{n}-{k+1}"
        a = {"id": rid, "floor": 1, "x": x, "y": y, "kind": "room", "number": n}
        if n in names and k == 0: a["name"] = names[n]
        if len(pts) > 1: a["duplicate"] = True
        anchors.append(a)
# уточнения по подписям справа от блока 1129-1131 в вестибюле
for a in anchors:
    if a["id"] == "1129-2": a["name"] = "Завхоз"
    if a["id"] == "1130-2": a["name"] = "Книжный магазин"
    if a["id"] == "1129": a["name"] = "ИТ-служба"
    if a["id"] == "1130": a["name"] = "ИТ-служба"
    if a["id"] == "1131": a["name"] = "ИТ-служба"
    if a["number"] in ("009", "010", "014"): a["approx"] = True
    where = {"1124": "северная часть", "1124-2": "восточное крыло",
             "1129": "северная часть", "1130": "северная часть", "1131": "северная часть",
             "1129-2": "вестибюль", "1130-2": "вестибюль", "1131-2": "вестибюль",
             "1132": "северная часть", "1133": "северная часть", "1134": "северная часть",
             "1132-2": "западное крыло", "1133-2": "западное крыло", "1134-2": "западное крыло"}
    if a["id"] in where: a["where"] = where[a["id"]]
    if a["id"] in ("1236", "1237"): a["via"] = "mc"
    if a["id"] == "1301": a["x"], a["y"] = 1371, 505   # старт у нижней точки круга, не из зала через дверь

pois = [
    ("entrance", "Главный вход", 1093, 1797),
    ("hall", "Центральный холл", 1371, 1322),   # центр между 1214, 1215, 1206, 1222
    ("cloak-1", "Гардероб", 1240, 1715),          # со стороны, обратной входу в блок; выход только влево/вправо
    ("cloak-2", "Гардероб (самообслуживания)", 1504, 1715),
]
for pid, name, x, y in pois:
    anchors.append({"id": pid, "floor": 1, "x": x, "y": y, "kind": "poi", "name": name})
stairs = [("s1-1", 290, 1322), ("s1-2", 1015, 1322), ("s1-3", 1723, 1322), ("s1-4", 2465, 1322),
          ("s1-5", 925, 2578), ("s1-6", 1815, 2578)]
for sid, x, y in stairs:
    anchors.append({"id": sid, "floor": 1, "x": x, "y": y, "kind": "stair", "name": "Лестница"})

corridors = [
    ("mc",   [[190, 1322], [2555, 1322]]),            # главный коридор запад-восток
    ("ln",   [[1108, 585], [1108, 1760]]),            # западная полоса центрального холла
    ("cn",   [[1371, 585], [1371, 1322]]),            # центральный проход от овала к центру холла
    ("rn",   [[1636, 585], [1636, 1750]]),            # восточная полоса холла
    ("xc",   [[790, 885], [1950, 885]]),              # северный поперечный коридор
    ("lob",  [[1108, 1715], [1636, 1715]]),           # проход по вестибюлю между стойкой и хранением гардеробов (выход влево/вправо)
    ("cc",   [[1371, 1322], [1371, 1715]]),           # центральный проход между гардеробами к центру холла
    ("lw",   [[928, 1760], [1108, 1760]]),            # вестибюль запад
    ("le",   [[1636, 1750], [1815, 1750]]),           # вестибюль восток
    ("ww",   [[928, 1640], [928, 2578]]),             # западное крыло, вертикаль
    ("wb",   [[800, 2578], [1270, 2578]]),            # западное крыло, низ
    ("ew",   [[1815, 1640], [1815, 2578]]),           # восточное крыло, вертикаль
    ("eb",   [[1475, 2578], [1950, 2578]]),           # восточное крыло, низ
    ("ov-w", [[1371, 585], [1371, 535], [1250, 500], [1195, 430], [1195, 375], [960, 375]]),
    ("ov-e", [[1371, 535], [1495, 500], [1550, 430], [1550, 375], [1790, 375]]),
]
out = {
    "corridors": [{"id": i, "floor": 1, "points": p} for i, p in corridors],
    "anchors": anchors,
}
json.dump(out, open("src/data/floor1.json", "w", encoding="utf8"), ensure_ascii=False, indent=1)
rooms = [a for a in anchors if a["kind"] == "room"]
print(len(rooms), "rooms;", "dups:", sorted({a["number"] for a in rooms if a.get("duplicate")}))
print(sorted(a["id"] for a in rooms))
